// @desc    Get all attendance records
// @route   GET /api/admin/attendance
// @access  Private (Admin)
const getAllAttendance = async (req, res) => {
  try {
    const { date, employeeId, page = 1, limit = 50 } = req.query;
    const filter = {};

    // Filter by date
    if (date) {
      filter.workDate = date;
    }

    // Filter by employee
    if (employeeId) {
      const employee = await User.findOne({ employeeId });
      if (employee) {
        filter.employee = employee._id;
      } else {
        return res.json({ records: [], pagination: { page: 1, limit: 50, total: 0, pages: 0 } });
      }
    }

    const skip = (parseInt(page) - 1) * parseInt(limit);

    const [records, total] = await Promise.all([
      Attendance.find(filter)
        .populate('employee', 'name email employeeId phone')
        .populate('corrections.correctedBy', 'name email')
        .sort({ workDate: -1, punchIn: -1 })
        .skip(skip)
        .limit(parseInt(limit)),
      Attendance.countDocuments(filter),
    ]);

    res.json({
      records,
      pagination: {
        page: parseInt(page),
        limit: parseInt(limit),
        total,
        pages: Math.ceil(total / parseInt(limit)),
      },
    });
  } catch (error) {
    console.error('Get all attendance error:', error);
    res.status(500).json({ message: 'Server error' });
  }
};

// @desc    Get dashboard statistics
// @route   GET /api/admin/dashboard
// @access  Private (Admin)
const getDashboardStats = async (req, res) => {
  try {
    const todayDate = getTodayDateIST();

    const [totalEmployees, pendingApprovals, todayRecords] = await Promise.all([
      User.countDocuments({ role: 'employee', status: 'approved' }),
      User.countDocuments({ role: 'employee', status: 'pending' }),
      Attendance.find({ workDate: todayDate }),
    ]);

    let presentCount = 0;
    let halfDayCount = 0;
    let absentCount = 0;
    let incompleteCount = 0;

    todayRecords.forEach((record) => {
      if (!record.isComplete) {
        incompleteCount++;
      } else if (record.status === 'present') {
        presentCount++;
      } else if (record.status === 'half-day') {
        halfDayCount++;
      } else if (record.status === 'absent') {
        absentCount++;
      }
    });

    // Employees who haven't punched in today
    const punchedInIds = todayRecords.map((r) => r.employee.toString());
    const notPunchedIn = totalEmployees - punchedInIds.length;

    res.json({
      totalEmployees,
      pendingApprovals,
      today: {
        date: todayDate,
        present: presentCount,
        halfDay: halfDayCount,
        absent: absentCount,
        incomplete: incompleteCount,
        notPunchedIn: notPunchedIn > 0 ? notPunchedIn : 0,
      },
    });
  } catch (error) {
    console.error('Get dashboard stats error:', error);
    res.status(500).json({ message: 'Server error' });
  }
};

// Validation for attendance correction
const correctAttendanceValidation = [
  body('field')
    .notEmpty()
    .withMessage('Field to correct is required')
    .isIn(['punchIn', 'punchOut', 'status', 'workingMinutes'])
    .withMessage('Invalid field. Allowed: punchIn, punchOut, status, workingMinutes'),
  body('newValue').notEmpty().withMessage('New value is required'),
  body('reason')
    .trim()
    .notEmpty()
    .withMessage('Reason for correction is required')
    .isLength({ min: 5 })
    .withMessage('Reason must be at least 5 characters'),
];

// @desc    Correct an attendance record
// @route   PUT /api/admin/attendance/:id/correct
// @access  Private (Admin)
const correctAttendance = [
  ...correctAttendanceValidation,
  async (req, res) => {
    try {
      const errors = validationResult(req);
      if (!errors.isEmpty()) {
        return res.status(400).json({ message: errors.array()[0].msg });
      }

      const { field, newValue, reason } = req.body;

      const attendance = await Attendance.findById(req.params.id);
      if (!attendance) {
        return res.status(404).json({ message: 'Attendance record not found' });
      }

      // Store old value
      const oldValue = attendance[field] != null ? attendance[field].toString() : 'null';

      // Push correction to audit trail
      attendance.corrections.push({
        correctedBy: req.user._id,
        field,
        oldValue,
        newValue: newValue.toString(),
        reason,
      });

      // Apply the correction
      if (field === 'punchIn' || field === 'punchOut') {
        const newDate = new Date(newValue);
        if (isNaN(newDate.getTime())) {
          return res.status(400).json({ message: 'Invalid date value' });
        }
        attendance[field] = newDate;

        // Recalculate working minutes and status if both punch times exist
        if (attendance.punchIn && attendance.punchOut) {
          const settings = await Settings.getSettings();
          attendance.workingMinutes = calculateWorkingMinutes(
            attendance.punchIn,
            attendance.punchOut
          );
          attendance.status = determineStatus(attendance.workingMinutes, settings);
          attendance.isComplete = true;
        }
      } else if (field === 'status') {
        const validStatuses = ['present', 'half-day', 'absent'];
        if (!validStatuses.includes(newValue)) {
          return res.status(400).json({ message: 'Invalid status value' });
        }
        attendance.status = newValue;
      } else if (field === 'workingMinutes') {
        const minutes = parseInt(newValue);
        if (isNaN(minutes) || minutes < 0) {
          return res.status(400).json({ message: 'Invalid working minutes value' });
        }
        attendance.workingMinutes = minutes;

        // Recalculate status based on new working minutes
        const settings = await Settings.getSettings();
        attendance.status = determineStatus(minutes, settings);
      }

      await attendance.save();

      // Re-fetch with populated fields
      const updated = await Attendance.findById(attendance._id)
        .populate('employee', 'name email employeeId')
        .populate('corrections.correctedBy', 'name email');

      res.json({
        message: 'Attendance record corrected successfully',
        attendance: updated,
      });
    } catch (error) {
      console.error('Correct attendance error:', error);
      res.status(500).json({ message: 'Server error during correction' });
    }
  },
];

// @desc    Finalize attendance day (mark absent for unpunched employees, flag incomplete punch-outs)
// @route   POST /api/admin/attendance/finalize-day
// @access  Private (Admin)
const finalizeAttendanceDay = async (req, res) => {
  try {
    const todayIST = getTodayDateIST();
    const targetDate = req.body.date || todayIST;
    const force = req.body.force === true;

    const settings = await Settings.getSettings();

    // If finalizing today's attendance, check if shift has ended unless forced
    if (targetDate === todayIST && !force) {
      const shiftEnded = isShiftEnded(settings.shiftEnd);
      if (!shiftEnded) {
        return res.status(400).json({
          message: `Shift ends at ${settings.shiftEnd}. Cannot finalize today's attendance before shift ends unless 'force: true' is specified.`,
        });
      }
    }

    // Get all approved employees
    const approvedEmployees = await User.find({ role: 'employee', status: 'approved' });

    let createdAbsentCount = 0;
    let incompleteCount = 0;

    for (const employee of approvedEmployees) {
      const existingRecord = await Attendance.findOne({
        employee: employee._id,
        workDate: targetDate,
      });

      if (!existingRecord) {
        // No punch-in: mark as absent after shift ends
        await Attendance.create({
          employee: employee._id,
          workDate: targetDate,
          status: 'absent',
          workingMinutes: 0,
          isComplete: true,
        });
        createdAbsentCount++;
      } else if (!existingRecord.isComplete && !existingRecord.punchOut) {
        // Forgot to punch out: mark status absent, leave isComplete false for admin review
        existingRecord.status = 'absent';
        existingRecord.isComplete = false;
        await existingRecord.save();
        incompleteCount++;
      }
    }

    res.json({
      message: `Attendance day ${targetDate} finalized successfully.`,
      targetDate,
      totalEmployees: approvedEmployees.length,
      absentMarked: createdAbsentCount,
      incompleteReviewed: incompleteCount,
    });
  } catch (error) {
    console.error('Finalize attendance day error:', error);
    res.status(500).json({ message: 'Server error during day finalization' });
  }
};

