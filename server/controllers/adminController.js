// @desc    Update system settings
// @route   PUT /api/admin/settings
// @access  Private (Admin)
const updateSettings = async (req, res) => {
  try {
    const { shiftStart, shiftEnd, breakDeduction, presentThreshold, halfDayThreshold } = req.body;
    const settings = await Settings.getSettings();

    if (shiftStart) settings.shiftStart = shiftStart;
    if (shiftEnd) settings.shiftEnd = shiftEnd;
    if (typeof breakDeduction === 'number') settings.breakDeduction = breakDeduction;
    if (typeof presentThreshold === 'number') settings.presentThreshold = presentThreshold;
    if (typeof halfDayThreshold === 'number') settings.halfDayThreshold = halfDayThreshold;

    await settings.save();
    res.json({ message: 'Settings updated successfully', settings });
  } catch (error) {
    console.error('Update settings error:', error);
    res.status(500).json({ message: 'Server error updating settings' });
  }
};

